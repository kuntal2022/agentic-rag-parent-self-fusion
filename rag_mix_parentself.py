@st.cache_resource(show_spinner="Connecting models...")
def get_models():
    return {
        "main": ChatOpenAI(model=MAIN_MODEL),
        "agent": ChatOpenAI(model=AGENT_MODEL),
        "judge": ChatOpenAI(model=JUDGE_MODEL),
        "embeddings": OpenAIEmbeddings(),
    }


@st.cache_resource(show_spinner="Opening persistent Chroma store...")
def get_vectorstore(_embeddings) -> Chroma:
    """Persistent Chroma collection — survives app restarts. Only populated
    (embedded) the first time it's empty; never rebuilt after that."""
    return Chroma(
        collection_name="campaign_intel",
        embedding_function=_embeddings,
        persist_directory=CHROMA_DIR,
    )


@st.cache_resource(show_spinner="Indexing campaign data (first run only — subsequent runs reuse the persisted index)...")
def build_index_and_retrievers(csv_path: str):
    models = get_models()
    vectorstore = get_vectorstore(models["embeddings"])

    parent_docstore = create_kv_docstore(LocalFileStore(PARENT_STORE_DIR))

    p_splitter = RecursiveCharacterTextSplitter(chunk_size=1000, chunk_overlap=100)
    c_splitter = RecursiveCharacterTextSplitter(chunk_size=300, chunk_overlap=50)

    parent_child_retriever = ParentDocumentRetriever(
        parent_splitter=p_splitter,
        child_splitter=c_splitter,
        docstore=parent_docstore,
        vectorstore=vectorstore,
    )

    already_indexed = vectorstore._collection.count() > 0
    df = None
    if not already_indexed:
        if not os.path.exists(csv_path):
            raise FileNotFoundError(
                f"No persisted index found at '{CHROMA_DIR}', and the source CSV "
                f"'{csv_path}' does not exist. Provide the CSV once so the index "
                f"can be built — future runs will not need it."
            )
        df = pd.read_csv(csv_path)
        parent_child_retriever.add_documents(build_documents(df))
    else:
        # Index already on disk — no CSV read, no embedding calls.
        df = pd.read_csv(csv_path) if os.path.exists(csv_path) else None

    self_query_retriever = SelfQueryRetriever.from_llm(
        llm=models["main"],
        vectorstore=vectorstore,
        metadata_field_info=METADATA_FIELD_INFO,
        structured_query_translator=SafeChromaTranslator(),
        document_contents=DOCUMENT_CONTENT_DESCRIPTION,
        search_type="mmr",
        search_kwargs={"k": 10, "lambda_mult": 0.5, "fetch_k": 30},
    )

    custom_retriever = SelfQueryParentChildRetriver(
        SelfQueryRetriever=self_query_retriever,
        parent_docstore=parent_docstore,
    )

    llm_extract_compressor = LLMChainExtractor.from_llm(llm=models["main"])
    filter_compressor = EmbeddingsFilter(embeddings=models["embeddings"], similarity_threshold=0.65)
    compressor_pipeline = DocumentCompressorPipeline(transformers=[filter_compressor, llm_extract_compressor])
    compression_retriever = ContextualCompressionRetriever(
        base_compressor=compressor_pipeline,
        base_retriever=custom_retriever,
    )

    return {
        "vectorstore": vectorstore,
        "custom_retriever": custom_retriever,
        "compression_retriever": compression_retriever,
        "df": df,
        "chunk_count": vectorstore._collection.count(),
    }


