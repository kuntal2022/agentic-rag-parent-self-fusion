# LangGraph state + schemas
# ---------------------------------------------------------------------------
class RagSchema(TypedDict):
    query: str
    context: str
    augmented_question: object
    decison: str
    agent_ans: str
    final_ans: str
    pandas_query: str
    regular_query: str
    verdict: str
    judge_decison: str
    judge_feedback: Annotated[List[str], add]
    max_try: int


class JudgeSchema(BaseModel):
    judge_decison: Literal["Rework", "Good"] = Field(description="If the answer is grounded then good else rework")
    judge_feedback: str = Field(description="Why the decision was taken and what improvement is needed")


class Deciosn(BaseModel):
    decison: Literal["Agent", "Regular", "Both"] = Field(
        description="Whether the query should go to the Agent (pandas) path, the Regular RAG path, or Both"
    )
    verdict: str = Field(description="Why this decision was taken")
    pandas_query: str
    regular_query: str


SYSTEM_PROMPT_REGULAR = """You are a rag agent
    -See the context and question given by the customer
    - answer only gounded truth you are getting from the context
    - If you don't see context which support the question say you don't know stritly"""

SYSTEM_PROMPT_AGENT = """You are a data analyst assistant.
- You are given a computed answer (from a pandas aggregation) along with the pandas query used.
- Your job is to present this computed answer clearly and confidently to the user in natural language.
- The computed answer IS the ground truth — do not second-guess it or say "I don't know" if a computed value is present.
- If Any number is there return the number in a natrual lanugae as per the query given.
- No assumtion should make without fact support
- only data driven insight nothing extra"""


def build_graph(retrievers: dict):
    models = get_models()
    model = models["main"]
    compression_retriever = retrievers["compression_retriever"]
    df = retrievers["df"]

    def make_pandas_agent():
        return create_pandas_dataframe_agent(
            llm=models["agent"],
            df=df,
            allow_dangerous_code=True,
            prefix=f"""You are a data analyst. Given the dataframe columns:
                {COLUMNS}
                write a pandas expression to answer the user's question.""",
        )

    def DecionNode(state: RagSchema):
        struct_llm = models["agent"].with_structured_output(Deciosn)
        system_prompt = f"""You are a query analyzer deciding whether the query should go to the pandas
        Agent path or the regular RAG path.
        - Break the query into a pandas-style sub-question for anything needing aggregation/comparison
          ('compare', 'greater than', 'which is the best', etc.)
        - The RAG system CANNOT answer aggregation-type questions — if you see any aggregation, return Agent strictly.
        - Column list: {COLUMNS}
        - If the query mixes both types, return Both, and draft both pandas_query and regular_query."""
        prompt = ChatPromptTemplate.from_messages(
            [("system", system_prompt), ("human", "Question : \n {question}")]
        )
        r = struct_llm.invoke(prompt.invoke({"question": state["query"]}))
        return {
            "decison": r.decison,
            "verdict": r.verdict,
            "pandas_query": r.pandas_query,
            "regular_query": r.regular_query,
        }

    def Deciosn_Router_final(state: RagSchema):
        return "Agent_Execution" if state["decison"] == "Agent" else "retriver_node"

    def retriver_node(state: RagSchema):
        context = "\n\n...\n".join(
            i.page_content for i in compression_retriever.invoke(state["query"]) if i.page_content is not None
        )
        return {"context": context}

    def Regular_Augmentation(state: RagSchema):
        prompt = ChatPromptTemplate.from_messages(
            [("system", SYSTEM_PROMPT_REGULAR), ("human", "Context :\n{context} \n\nQuestion \n{question}")]
        )
        return {"augmented_question": prompt.invoke({"context": state["context"], "question": state["query"]})}

    def Agent_Execution(state: RagSchema):
        result = make_pandas_agent().invoke(state["query"])
        return {"agent_ans": result.get("output", "No result found")}

    def combine_node(state: RagSchema):
        pandas_query = state["pandas_query"]
        result_pandas_raw = make_pandas_agent().invoke(
            f"Original query is: {state['query']} the modified query for you is {pandas_query} "
            f"answer wisely for the part of the query where you need this pandas query reference "
            f"if the aggregated part is there and pandas query is not blank"
        )
        result_pandas = result_pandas_raw.get("output", "No result found")
        context = state["context"] + "\n\n **Aggregated part of the query answer is given below**\n\n" + result_pandas

        prompt = ChatPromptTemplate.from_messages(
            [
                (
                    "system",
                    """You are a data analyst assistant. You are given two pieces of information:
            1. Retrieved context (qualitative campaign descriptions)
            2. A computed data answer (from pandas aggregation/comparison)

            Your job: Answer the user's FULL question using BOTH pieces of information.
            - If the question has multiple parts (e.g., a comparison AND a descriptive part),
            make sure your answer addresses EVERY part.
            - Use the computed answer for any numeric/comparison claims.
            - Use the retrieved context for descriptive/qualitative claims.
            - Do not omit any part of the original question.""",
                ),
                (
                    "human",
                    "Retrieved Context:\n{context}\n\nOriginal Question:\n{question}\n\n"
                    "Provide a complete answer covering all parts of the question.",
                ),
            ]
        )
        augmented_question = prompt.invoke({"context": context, "question": state["query"]})
        return {"augmented_question": augmented_question, "agent_ans": result_pandas}

    def Agent_Augmentation(state: RagSchema):
        prompt = ChatPromptTemplate.from_messages(
            [
                ("system", SYSTEM_PROMPT_AGENT),
                ("human", "Context :\n{context} \n\nQuestion \n{question} \n\n Pandas Query : {pandas_query}"),
            ]
        )
        return {
            "augmented_question": prompt.invoke(
                {"context": state["agent_ans"], "question": state["query"], "pandas_query": state["pandas_query"]}
            )
        }

    def Retrive_router(state: RagSchema):
        return "combine_node" if state["decison"] == "Both" else "Regular_Augmentation"

    def LLm_AS_judge(state: RagSchema):
        judge_llm = models["judge"].with_structured_output(JudgeSchema)
        max_try = state.get("max_try", 0)

        if max_try <= 2:
            prompt = ChatPromptTemplate.from_messages(
                [
                    (
                        "system",
                        """You are a Rag System final answer evaluator. See the query, context, and agent answer
            and evaluate whether the answer is grounded; if not, give feedback to the generator.
            - Sometimes agent answer can be None, sometimes context can be None.
            - If context is blank, treat the Agent Answer as the context (noting it came from a pandas tool call).
            - If both context and agent answer are blank, say you don't have an idea.
            - If both are present, treat context as the combination of both — never drop the aggregated part.
            - Output structure should be bullet points, one per paragraph.""",
                    ),
                    (
                        "human",
                        "Context: \n{Context},\n"
                        "Agent Answer: \n{agent_ans},\n"
                        "Question : {query} -> Pandas Part {pandas_query} -> Regular Query part {reqular_query}",
                    ),
                ]
            )
            chain = prompt | judge_llm
            result = chain.invoke(
                {
                    "Context": state.get("context", "No context"),
                    "agent_ans": state.get("agent_ans", None),
                    "query": state["query"],
                    "pandas_query": state.get("pandas_query", "Not found"),
                    "reqular_query": state.get("regular_query", "Not found"),
                }
            )
            return {
                "judge_decison": result.judge_decison,
                "judge_feedback": [result.judge_feedback],
                "max_try": max_try + 1,
            }
        return {"judge_decison": "Good", "judge_feedback": [""], "max_try": max_try}

    def route_judge(state: RagSchema):
        return END if state["judge_decison"] == "Good" else "Generation"

    def Generation(state: RagSchema):
        max_try = state.get("max_try", 0)
        feedback_list = state.get("judge_feedback", [])
        feedback = "\n\n...\n".join(feedback_list)

        aug_q_base = state["augmented_question"]
        if hasattr(aug_q_base, "to_messages"):
            aug_q_base = aug_q_base.to_messages()

        if len(feedback) >= 5 and max_try <= 2:
            feedback_msg = HumanMessage(
                content="The upper response is not enough, the Judge has passed feedback, see that and "
                "correct that.\nJudge Feedback \n" + feedback
            )
            aug_q = aug_q_base + [feedback_msg]
        else:
            aug_q = aug_q_base

        response = model.invoke(aug_q)
        return {"final_ans": response.content}

    builder = StateGraph(RagSchema)
    builder.add_node("DecionNode", DecionNode)
    builder.add_node("retriver_node", retriver_node)
    builder.add_node("Regular_Augmentation", Regular_Augmentation)
    builder.add_node("Agent_Augmentation", Agent_Augmentation)
    builder.add_node("Generation", Generation)
    builder.add_node("Agent_Execution", Agent_Execution)
    builder.add_node("combine_node", combine_node)
    builder.add_node("LLm_AS_judge", LLm_AS_judge)

    builder.add_edge(START, "DecionNode")
    builder.add_conditional_edges(
        "DecionNode", Deciosn_Router_final, {"retriver_node": "retriver_node", "Agent_Execution": "Agent_Execution"}
    )
    builder.add_conditional_edges(
        "retriver_node", Retrive_router, {"Regular_Augmentation": "Regular_Augmentation", "combine_node": "combine_node"}
    )
    builder.add_edge("Regular_Augmentation", "Generation")
    builder.add_edge("Agent_Execution", "Agent_Augmentation")
    builder.add_edge("Agent_Augmentation", "Generation")
    builder.add_edge("combine_node", "Generation")
    builder.add_edge("Generation", "LLm_AS_judge")
    builder.add_conditional_edges("LLm_AS_judge", route_judge, {END: END, "Generation": "Generation"})

    # In-memory checkpointer, wired at compile time as requested — gives the
    # graph real checkpointing/thread support (see module docstring for why
    # each chat turn still runs on its own fresh thread_id).
    return builder.compile(checkpointer=InMemorySaver())


@st.cache_resource(show_spinner="Compiling the agentic RAG graph...")
def get_app(csv_path: str):
    retrievers = build_index_and_retrievers(csv_path)
    graph = build_graph(retrievers)
    return graph, retrievers


