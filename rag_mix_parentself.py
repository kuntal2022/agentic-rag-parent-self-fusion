class SafeChromaTranslator(ChromaTranslator):
    """Coerces numpy/pandas scalar filter values to native Python int/float
    before Chroma validates the `where` clause."""

    def visit_comparison(self, comparison: Comparison) -> dict:
        value = comparison.value
        if isinstance(value, (int, float)) or hasattr(value, "item"):
            try:
                value = float(value) if isinstance(value, float) or hasattr(value, "item") else int(value)
            except (TypeError, ValueError):
                pass
            comparison = Comparison(comparator=comparison.comparator, attribute=comparison.attribute, value=value)
        return super().visit_comparison(comparison)


class SelfQueryParentChildRetriver(BaseRetriever):
    """Runs Self-Query retrieval over child chunks, then resolves each hit
    back to its full parent Document."""

    SelfQueryRetriever: BaseRetriever
    parent_docstore: object

    def _get_relevant_documents(self, query: str) -> List[Document]:
        child_docs = self.SelfQueryRetriever.invoke(query)
        parent_ids = {doc.metadata["doc_id"] for doc in child_docs if "doc_id" in doc.metadata}
        parent_docs = [self.parent_docstore.mget([pid])[0] for pid in parent_ids]
        return [d for d in parent_docs if d is not None]


def build_documents(df: pd.DataFrame) -> List[Document]:
    docs = []
    for _, row in df.iterrows():
        docs.append(
            Document(
                page_content=row["combined_description"],
                metadata={
                    "campaign_id": row["campaign_id"],
                    "territory": row["territory"],
                    "quarter": row["quarter"],
                    "cohort": row["cohort"],
                    "revenue": float(row["revenue"]),
                    "tg_count": int(row["tg_count"]),
                    "cg_count": int(row["cg_count"]),
                    "lift_percent": float(row["lift_percent"]),
                    "response_rate_percent": float(row["response_rate_percent"]),
                    "atbms": float(row["atbms"]),
                },
            )
        )
    return docs


