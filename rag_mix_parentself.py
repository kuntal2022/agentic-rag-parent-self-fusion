"""
Streamlit chat app for the Parent-Child + Self-Query "fusion" retriever,
wrapped in a LangGraph agentic router (vector RAG vs. pandas aggregation vs. both)
with an LLM-as-judge self-correction loop.

Design notes (why this differs slightly from the exploratory notebook):

- The Chroma vector store is PERSISTENT (`persist_directory=CHROMA_DIR`) and the
  parent-document store is also persisted to disk (`LocalFileStore` instead of
  `InMemoryStore`). On startup we check whether the collection already has
  vectors; if it does, we skip re-reading the CSV and re-embedding entirely.
  This means the (expensive, API-billed) indexing step only ever runs once —
  every subsequent `streamlit run` reuses the existing on-disk index.

- `st.cache_resource` wraps every expensive object (embeddings, vectorstore,
  retrievers, the compiled graph) so Streamlit's rerun-on-every-interaction
  model doesn't reconstruct them on every keystroke/message.

- The compiled LangGraph app uses `InMemorySaver` as its checkpointer, as
  requested, so the graph has real checkpointing support. Each user turn is
  run on a *fresh* thread_id rather than one shared thread — `judge_feedback`
  uses an additive reducer (`Annotated[List[str], add]`), so reusing one
  thread across unrelated questions would make old feedback bleed into new
  runs (the additive reducer has no way to be reset mid-thread). The visible
  chat history shown in the UI is tracked separately in
  `st.session_state.chat_history`, so the conversation still reads as a
  normal chat even though each turn is graph-isolated.
"""

